#!/usr/bin/env node
/**
 * THE BREAKPOINT SHEET.
 *
 * The instrument reads cliffs out of a stylesheet with the LEGACY syntax —
 * `(min-width: 640px)`. This build emits the modern range syntax —
 * `@media (width >= 40rem)` — which the same reader does not recognise. So
 * the cliffs are read out of the real, built CSS and written down again in
 * the form the instrument can read. Nothing here is hand-listed: if the
 * breakpoints change in the build, this sheet changes with them.
 *
 * Both mirrors use it: the built site and the deployed bytes. A mirror that
 * cannot state its cliffs is measured at the widths somebody listed, which
 * are the widths where nothing changes.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

/**
 * The cliffs in a stylesheet, in the syntax the instrument reads.
 * @param {string[]} cssFiles absolute paths to stylesheets
 * @returns {string[]} e.g. ["min-width: 640px", "max-width: 1023px"]
 */
export function cliffsOf(cssFiles) {
  const cliffs = new Set();
  for (const file of cssFiles) {
    const text = readFileSync(file, "utf8");
    // Only VIEWPORT cliffs belong on this sheet. A container query is a
    // width of a BLOCK, not of the screen: the sheet that tells the
    // instrument where the screen changes must not claim that the screen
    // changes at 560px because a legend changes its columns there.
    const media = text.match(/@media[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g) || [];
    const viewport = media.join("\n");
    for (const m of viewport.matchAll(/\((?:min|max)-width:\s*([\d.]+)(px|rem|em)\)/gi)) {
      const n = parseFloat(m[1]);
      if (!Number.isFinite(n) || n <= 0) continue;
      const px = Math.round(m[2] === "px" ? n : n * 16);
      cliffs.add(`min-width: ${px}px`);
    }
    // Modern range syntax: (width >= 40rem), (width <= 63.999rem), and the
    // parenthesised comparisons Tailwind writes in its compiled output.
    for (const m of viewport.matchAll(/\(\s*(?:min-|max-)?width\s*(>=|<=|>|<)\s*([\d.]+)(px|rem|em)\s*\)/gi)) {
      const n = parseFloat(m[2]);
      if (!Number.isFinite(n) || n <= 0) continue;
      const px = Math.round(m[3] === "px" ? n : n * 16);
      cliffs.add(`${m[1] === "<=" || m[1] === "<" ? "max-width" : "min-width"}: ${px}px`);
    }
  }
  return [...cliffs].sort();
}

/**
 * Write the sheet where the instrument looks for it.
 * @param {string} cssDir the directory the instrument reads
 * @param {string[]} cliffs
 */
export function writeSheet(cssDir, cliffs) {
  const sheet = [
    "/* Generated by scripts/spatial/breakpoints.mjs from the real stylesheet.",
    "   The instrument reads breakpoints in the legacy syntax; the build emits",
    "   the modern range syntax. These are the real cliffs of the real sheet. */",
    ...cliffs.map((c) => `@media (${c}) {}`),
    "",
  ].join("\n");
  writeFileSync(path.join(cssDir, "breakpoints.css"), sheet);
}
