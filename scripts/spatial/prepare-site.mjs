#!/usr/bin/env node
/**
 * PREPARE THE SITE THE GATE MEASURES.
 *
 * The MSH instrument is byte-identical to the one the law names, so it
 * cannot be edited to suit this project. It looks for a stylesheet at
 * <site>/_next/static/css — the path a Next.js build uses — and this is a
 * Vite build, so the sweep falls back to "the project's own widths" and
 * never measures where the CSS actually changes. That is the exact blindness
 * the instrument reports in its notes, and a layout checked only at the
 * widths somebody listed is checked at the widths where nothing changes.
 *
 * So the built site is mirrored into .spatial-site/ with the real, built
 * stylesheet ALSO placed where the instrument looks for it. The bytes served
 * are the bytes that ship; only the path of the stylesheet is added, and the
 * mirror is never deployed.
 */
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..", "..");
const SITE = path.join(ROOT, "dist");
const MIRROR = path.join(ROOT, ".spatial-site");
const CSS_DIR = path.join(MIRROR, "_next", "static", "css");
/* The falsifier needs a page with a hole in it. Our own pages have none —
   that is the point of them — so the proof that the gate catches a hole has
   nothing to catch unless a fixture page carries one. The fixture is a
   measure of the instrument, not of the product: it lives in the mirror,
   which is never deployed and never committed. */
const WITH_FIXTURE = process.argv.includes("--with-fixture");

if (!existsSync(path.join(SITE, "index.html"))) {
  console.error(`\nFAIL — there is no built site at ${path.relative(ROOT, SITE)}.\n  Run the build first.\n`);
  process.exit(1);
}

rmSync(MIRROR, { recursive: true, force: true });
mkdirSync(MIRROR, { recursive: true });
cpSync(SITE, MIRROR, { recursive: true });

// The instrument scans these files for media queries and container queries.
const ASSETS = path.join(MIRROR, "assets");
const sheets = existsSync(ASSETS)
  ? readdirSync(ASSETS).filter((f) => f.endsWith(".css"))
  : [];
if (!sheets.length) {
  console.error(
    `\nFAIL — no built stylesheet found in ${path.relative(ROOT, ASSETS)}.\n` +
      "  The gate cannot find the breakpoints of a site with no CSS.\n",
  );
  process.exit(1);
}
mkdirSync(CSS_DIR, { recursive: true });
for (const f of sheets) {
  cpSync(path.join(ASSETS, f), path.join(CSS_DIR, f));
}

/**
 * The breakpoint sheet.
 *
 * The instrument reads cliffs out of a stylesheet with the LEGACY syntax —
 * `(min-width: 640px)`. This build emits the modern range syntax —
 * `@media (width >= 40rem)` — which the same reader does not recognise. So
 * the cliffs are read out of the real, built CSS and written down again in
 * the form the instrument can read. Nothing here is hand-listed: if the
 * breakpoints change in the build, this sheet changes with them.
 */
const cliffs = new Set();
for (const f of sheets) {
  const text = readFileSync(path.join(ASSETS, f), "utf8");
  for (const m of text.matchAll(/\((?:min|max)-width:\s*([\d.]+)(px|rem|em)\)/gi)) {
    const n = parseFloat(m[1]);
    if (!Number.isFinite(n) || n <= 0) continue;
    const px = Math.round(m[2] === "px" ? n : n * 16);
    cliffs.add(`min-width: ${px}px`);
  }
  // Modern range syntax: (width >= 40rem), (width <= 63.999rem), and the
  // parenthesised comparisons Tailwind writes in its compiled output.
  for (const m of text.matchAll(/\(\s*(?:min-|max-)?width\s*(>=|<=|>|<)\s*([\d.]+)(px|rem|em)\s*\)/gi)) {
    const n = parseFloat(m[2]);
    if (!Number.isFinite(n) || n <= 0) continue;
    const px = Math.round(m[3] === "px" ? n : n * 16);
    cliffs.add(`${m[1] === "<=" || m[1] === "<" ? "max-width" : "min-width"}: ${px}px`);
  }
}
const sheet = [
  "/* Generated by scripts/spatial/prepare-site.mjs from the built CSS.",
  "   The instrument reads breakpoints in the legacy syntax; the build emits",
  "   the modern range syntax. These are the real cliffs of the real sheet. */",
  ...[...cliffs].sort().map((c) => `@media (${c}) {}`),
  "",
].join("\n");
writeFileSync(path.join(CSS_DIR, "breakpoints.css"), sheet);

const bytes = sheets.reduce((n, f) => n + statSync(path.join(CSS_DIR, f)).size, 0);
console.log(
  `  · spatial site ready: ${path.relative(ROOT, MIRROR)} — ` +
    `${sheets.length} stylesheet(s) (${Math.round(bytes / 1024)} kB) also placed where the instrument looks for them, ` +
    `${cliffs.size} breakpoint(s) stated for the sweep`,
);

/**
 * The fixture page, for the falsifier only.
 *
 * It carries the two things the instrument's own rules about the RECEIPT
 * need in order to bite: a chrome band with a height (so the rule that
 * catches a header growing has a header to grow), and a hole with a number
 * in it (so the rules that catch a hole growing, a hole shrinking, and a
 * decision whose numbers were never recorded have a hole to move). Both are
 * deliberately broken; neither is part of the product.
 */
if (WITH_FIXTURE) {
  const dir = path.join(MIRROR, "sl-defect");
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    path.join(dir, "index.html"),
    `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>MSH fixture — a page with a hole in it</title>
<style>
  html,body{margin:0;padding:0;background:#fff;color:#111;font:14px/1.4 system-ui,sans-serif}
  header{height:72px;border-bottom:1px solid #e5e5e5;display:flex;align-items:center;padding:0 16px}
  main{padding:16px}
  h1{font-size:32px;margin:0 0 16px}
  .sl-defect{display:flex;flex-direction:column}
  .sl-defect-a{height:24px;background:#d8d8d8}
  .sl-defect-b{height:24px;background:#d8d8d8;margin-top:260px}
</style>
</head>
<body>
<header><strong>Fixture</strong></header>
<main id="content">
<h1>A page with a hole in it</h1>
<button type="button" style="min-height:44px;border:1px solid #111;background:#fff;padding:0 16px">Act here</button>
<div class="sl-defect"><div class="sl-defect-a"></div><div class="sl-defect-b"></div></div>
</main>
</body>
</html>`,
  );
  console.log("  · spatial fixture page added (sl-defect) — a chrome band and a hole, for the falsifier only");
}
